"""Local STDIO MCP server: MiniMax H3 video generation with one pasted API key.

This is the version that runs ON THE STUDENT'S COMPUTER. WorkBuddy launches it
as a subprocess and talks MCP over stdin/stdout -- no host, no port, no public
URL, no group tokens, no central server.

Each student group needs EXACTLY ONE credential: its single TokenHub API key
pasted as the first line of `api-key.txt` next to this file. There is no second
key, no group token, no SecretId/SecretKey, no `user` field, and no environment
variable override. `api-key.txt` is the single source of truth and is gitignored.

The key is never in the MCP config, never in git, and never sent anywhere except
as one `Authorization: Bearer ...` header to the TokenHub endpoint. It is read
on every tool call, so pasting or rotating it never requires a restart.

Finished videos are written to `videos/<uuid>.mp4` in this directory and the
tool returns a local absolute `video_path`. There is no URL to serve.

CRITICAL for stdio transport: never print() to stdout. All diagnostics go to
stderr, because stdout carries the JSON-RPC stream.

Run directly (only for debugging):
    python server.py
WorkBuddy runs it via the config generated by setup_mcp.py.
"""

from __future__ import annotations

import asyncio
import json
import os
import threading
import time
import uuid
from datetime import date
from pathlib import Path
from typing import Any

from mcp.server import MCPServer

import tokenhub

BASE_DIR = Path(__file__).resolve().parent
KEY_FILE = Path(os.environ.get("TOKENHUB_KEY_FILE", str(BASE_DIR / "api-key.txt")))
OUTPUT_DIR = Path(os.environ.get("VIDEO_OUTPUT_DIR", str(BASE_DIR / "videos")))
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
USAGE_FILE = Path(os.environ.get("USAGE_FILE", str(BASE_DIR / "usage.jsonl")))

MAX_PER_DAY = int(os.environ.get("MAX_VIDEOS_PER_DAY", "60"))
VIDEO_TTL_HOURS = int(os.environ.get("VIDEO_TTL_HOURS", "72"))
POLL_INTERVAL = int(os.environ.get("POLL_INTERVAL_SECONDS", "5"))

_usage_lock = threading.Lock()
PLACEHOLDER_MARKERS = ("PASTE_", "YOUR_API_KEY", "REPLACE_WITH", "EXAMPLE")
KEY_SOURCE = "api-key.txt (single file, one key)"
CREDENTIALS_REQUIRED = 1


def load_api_key() -> str:
    """Return the ONE key from api-key.txt. No env override, no second source.

    Deliberately there is no environment-variable fallback: a group needs
    exactly one credential in exactly one place. Reading the file on every
    call means pasting (or rotating) the key needs no restart.
    """
    key = ""
    if KEY_FILE.exists():
        lines = KEY_FILE.read_text(encoding="utf-8").strip().splitlines()
        key = lines[0].strip() if lines else ""
    if not key or any(marker in key.upper() for marker in PLACEHOLDER_MARKERS):
        raise RuntimeError(
            "No TokenHub API key configured. Paste your single API key into "
            f"{KEY_FILE} (one line, no quotes), then try again. "
            "Do not put the key in the MCP config or commit it to git."
        )
    return key


def _log(**fields: Any) -> None:
    record = {"ts": time.time(), "date": date.today().isoformat(), **fields}
    with _usage_lock:
        with USAGE_FILE.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(record, ensure_ascii=False) + "\n")


def _submits_today() -> int:
    if not USAGE_FILE.exists():
        return 0
    today = date.today().isoformat()
    count = 0
    with USAGE_FILE.open("r", encoding="utf-8") as fh:
        for line in fh:
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            if rec.get("date") == today and rec.get("action") == "submit":
                count += 1
    return count


async def _poll(api_key: str, task_id: str, wait_seconds: int) -> dict[str, Any]:
    deadline = time.monotonic() + max(0, wait_seconds)
    while True:
        result = await asyncio.to_thread(tokenhub.query, api_key, task_id)
        if result["status"] == tokenhub.SUCCESS_STATUS or result["status"] in tokenhub.FAIL_STATUSES:
            return result
        if time.monotonic() >= deadline:
            result["timed_out"] = True
            return result
        await asyncio.sleep(POLL_INTERVAL)


async def _finish(task_id: str, result: dict[str, Any]) -> dict[str, Any]:
    status = result["status"]
    if status in tokenhub.FAIL_STATUSES:
        _log(action="fail", task_id=task_id, message=result["message"], status=status)
        return {
            "ok": False,
            "task_id": task_id,
            "status": status,
            "error": result["message"] or f"TokenHub task {status}",
        }
    if result.get("timed_out") or status != tokenhub.SUCCESS_STATUS:
        return {
            "ok": True,
            "task_id": task_id,
            "status": status,
            "pending": True,
            "hint": "Still generating. Call check_video with this task_id in a minute.",
        }

    video_url = result["video_url"]
    if not video_url:
        return {"ok": False, "task_id": task_id, "error": "Task succeeded but no task.content.url was returned"}

    filename = f"{uuid.uuid4().hex}.mp4"
    dest = str(OUTPUT_DIR / filename)
    await asyncio.to_thread(tokenhub.save_video, video_url, dest)
    size = os.path.getsize(dest)
    _log(
        action="done",
        task_id=task_id,
        file=filename,
        model=result.get("model", ""),
        resolution=result.get("resolution", ""),
        duration=result.get("duration"),
        total_tokens=result.get("total_tokens"),
        bytes=size,
    )
    return {
        "ok": True,
        "task_id": task_id,
        "status": tokenhub.SUCCESS_STATUS,
        "pending": False,
        "model": result.get("model") or tokenhub.MODEL,
        "resolution": result.get("resolution", ""),
        "duration": result.get("duration"),
        "total_tokens": result.get("total_tokens"),
        "video_path": dest,
        "file_size_bytes": size,
        "hint": "This is a local file. Open it directly; no download URL is needed.",
    }


mcp_server = MCPServer(
    "hailuo-video",
    instructions=(
        "Generate short videos with MiniMax H3 (minimax-video-h3) on Tencent Cloud "
        "TokenHub. Call generate_video with a scene description; it returns "
        "video_path, a local absolute path to the finished MP4. Generation takes "
        "1-3 minutes. If it returns pending=true, call check_video with that task_id. "
        "Exactly one credential is needed: the group's single API key in "
        "api-key.txt beside the server. It is read on every call, so pasting it "
        "needs no restart. Never ask the user for a second key or token."
    ),
)


@mcp_server.tool()
def video_capabilities() -> dict[str, Any]:
    """Report the model, endpoint, parameter ranges, and whether the key is configured."""
    try:
        load_api_key()
        key_state = "configured"
    except RuntimeError as exc:
        key_state = f"MISSING - {exc}"
    return {
        "transport": "stdio (local)",
        "key_configured": key_state == "configured",
        "key_status": key_state,
        "key_source": KEY_SOURCE,
        "key_file": str(KEY_FILE),
        "credentials_required": CREDENTIALS_REQUIRED,
        "model": tokenhub.MODEL,
        "also_available": tokenhub.MODEL_H3_MAX,
        "base_url": tokenhub.BASE_URL,
        "submit": f"POST {tokenhub.SUBMIT_PATH}",
        "query": f"GET {tokenhub.QUERY_PATH}",
        "auth": "Authorization: Bearer <single API key> (no SecretId/SecretKey, no user field)",
        "duration_seconds_h3": [tokenhub.MIN_DURATION, tokenhub.MAX_DURATION],
        "duration_seconds_h3_max": [tokenhub.MIN_DURATION_MAX_MODEL, tokenhub.MAX_DURATION],
        "resolutions_h3": list(tokenhub.H3_RESOLUTIONS),
        "resolutions_h3_max": list(tokenhub.H3_MAX_RESOLUTIONS),
        "ratios": list(tokenhub.RATIOS),
        "default": {"duration": 6, "resolution": "768P", "ratio": "16:9"},
        "daily_cap": MAX_PER_DAY,
        "video_output_dir": str(OUTPUT_DIR),
        "note": "Text-to-video only. ratio is required and cannot be 'adaptive'. Result URLs expire in 12h, so this server downloads the MP4 locally for you.",
    }


@mcp_server.tool()
async def submit_video(
    prompt: str,
    duration: int = 6,
    resolution: str = "768P",
    ratio: str = "16:9",
    model: str = "",
) -> dict[str, Any]:
    """Submit a MiniMax H3 video job without waiting. Returns a task_id for check_video."""
    try:
        api_key = load_api_key()
    except RuntimeError as exc:
        return {"ok": False, "key_configured": False, "error": str(exc)}
    if _submits_today() >= MAX_PER_DAY:
        return {"ok": False, "error": f"Daily generation cap ({MAX_PER_DAY}) reached on this machine."}
    payload = tokenhub.build_payload(
        prompt=prompt, duration=duration, resolution=resolution, ratio=ratio, model=model
    )
    task_id = await asyncio.to_thread(tokenhub.submit, api_key, payload)
    _log(action="submit", task_id=task_id, **{k: v for k, v in payload.items() if k != "content"})
    return {"ok": True, "task_id": task_id, "status": "queued", "model": payload["model"]}


@mcp_server.tool()
async def check_video(task_id: str, wait_seconds: int = 0) -> dict[str, Any]:
    """Poll a submitted job. Set wait_seconds > 0 to wait briefly for completion."""
    try:
        api_key = load_api_key()
    except RuntimeError as exc:
        return {"ok": False, "key_configured": False, "error": str(exc)}
    result = await _poll(api_key, task_id, max(0, wait_seconds))
    return await _finish(task_id, result)


@mcp_server.tool()
async def generate_video(
    prompt: str,
    duration: int = 6,
    resolution: str = "768P",
    ratio: str = "16:9",
    model: str = "",
    wait_seconds: int = 300,
) -> dict[str, Any]:
    """Generate a video and return video_path, a local absolute path to the MP4.

    Takes 1-3 minutes. If it returns pending=true, call check_video with the
    returned task_id. Cheapest test: duration=4, resolution=768P.
    """
    try:
        api_key = load_api_key()
    except RuntimeError as exc:
        return {"ok": False, "key_configured": False, "error": str(exc)}
    if _submits_today() >= MAX_PER_DAY:
        return {"ok": False, "error": f"Daily generation cap ({MAX_PER_DAY}) reached on this machine."}
    payload = tokenhub.build_payload(
        prompt=prompt, duration=duration, resolution=resolution, ratio=ratio, model=model
    )
    task_id = await asyncio.to_thread(tokenhub.submit, api_key, payload)
    _log(action="submit", task_id=task_id, **{k: v for k, v in payload.items() if k != "content"})
    result = await _poll(api_key, task_id, wait_seconds)
    return await _finish(task_id, result)


def _cleanup_loop() -> None:
    cutoff = VIDEO_TTL_HOURS * 3600
    while True:
        now = time.time()
        for path in OUTPUT_DIR.glob("*.mp4"):
            try:
                if now - path.stat().st_mtime > cutoff:
                    path.unlink()
            except OSError:
                pass
        time.sleep(3600)


threading.Thread(target=_cleanup_loop, daemon=True).start()


if __name__ == "__main__":
    # The SDK's stdio_server() claims fd 1 and diverts stray output to stderr
    # itself, so our code simply must never write to stdout.
    mcp_server.run(transport="stdio")
